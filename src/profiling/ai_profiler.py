import argparse
import hashlib
import json
import os
import re
import time
from pathlib import Path

from openai import OpenAI


# ============================================================
# CONFIGURATION
# ============================================================

DEFAULT_METADATA_FILE = Path(
    "output/metadata.json"
)

DEFAULT_OUTPUT_FILE = Path(
    "output/data_dictionary.json"
)

DEFAULT_CACHE_FILE = Path(
    "output/data_dictionary_cache.json"
)

OPENROUTER_MODEL = "openrouter/free"

OPENROUTER_BASE_URL = (
    "https://openrouter.ai/api/v1"
)

MAX_RETRIES = 4

RETRY_DELAY_SECONDS = 5


# ============================================================
# OPENROUTER CLIENT
# ============================================================

def create_openrouter_client():
    """
    Create and return an OpenRouter client.

    The API key is read from the OPENROUTER_API_KEY
    environment variable.
    """

    api_key = os.getenv(
        "OPENROUTER_API_KEY"
    )

    if not api_key:

        raise RuntimeError(
            "OPENROUTER_API_KEY is not configured. "
            "Please configure your OpenRouter API key "
            "as an environment variable or Codespaces secret."
        )

    try:

        client = OpenAI(
            api_key=api_key,
            base_url=OPENROUTER_BASE_URL
        )

    except Exception as error:

        raise RuntimeError(
            "Unable to initialize the OpenRouter client. "
            "Make sure your OpenRouter API credentials "
            "are configured correctly."
        ) from error

    return client


# ============================================================
# LOAD METADATA
# ============================================================

def load_metadata(metadata_file):
    """
    Load metadata JSON generated by extract_metadata.py.
    """

    metadata_file = Path(
        metadata_file
    )

    if not metadata_file.exists():

        raise FileNotFoundError(
            f"Metadata file not found: {metadata_file}"
        )

    with open(
        metadata_file,
        "r",
        encoding="utf-8"
    ) as file:

        metadata = json.load(file)

    if not isinstance(
        metadata,
        list
    ):

        raise ValueError(
            "Metadata JSON must contain a list of "
            "column metadata objects."
        )

    if len(metadata) == 0:

        raise ValueError(
            "Metadata file contains no column information."
        )

    return metadata


# ============================================================
# DATASET / METADATA FINGERPRINT
# ============================================================

def create_metadata_fingerprint(metadata):
    """
    Create a deterministic SHA-256 fingerprint from metadata.

    The fingerprint allows the profiler to determine whether
    the cached AI data dictionary belongs to the current dataset.
    """

    canonical_metadata = json.dumps(
        metadata,
        sort_keys=True,
        separators=(",", ":"),
        default=str
    )

    return hashlib.sha256(
        canonical_metadata.encode("utf-8")
    ).hexdigest()


# ============================================================
# CACHE HANDLING
# ============================================================

def load_cached_dictionary(
    output_file,
    cache_file,
    metadata
):
    """
    Load an existing AI data dictionary only if its cache
    fingerprint matches the current dataset metadata.

    Returns
    -------
    list or None
    """

    output_file = Path(
        output_file
    )

    cache_file = Path(
        cache_file
    )

    if not output_file.exists():

        return None

    if not cache_file.exists():

        return None

    try:

        with open(
            cache_file,
            "r",
            encoding="utf-8"
        ) as file:

            cache = json.load(file)

    except Exception:

        return None

    if not isinstance(
        cache,
        dict
    ):

        return None

    current_fingerprint = (
        create_metadata_fingerprint(
            metadata
        )
    )

    cached_fingerprint = cache.get(
        "metadata_fingerprint"
    )

    if cached_fingerprint != current_fingerprint:

        return None

    try:

        with open(
            output_file,
            "r",
            encoding="utf-8"
        ) as file:

            dictionary = json.load(file)

    except Exception:

        return None

    if not validate_result(
        dictionary,
        metadata
    ):

        return None

    return dictionary


def save_cache_metadata(
    cache_file,
    metadata
):
    """
    Save the fingerprint associated with the current
    AI data dictionary.
    """

    cache_file = Path(
        cache_file
    )

    cache_file.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    fingerprint = (
        create_metadata_fingerprint(
            metadata
        )
    )

    cache = {
        "metadata_fingerprint": fingerprint,
        "columns": [
            item.get("column_name")
            for item in metadata
            if isinstance(item, dict)
        ]
    }

    with open(
        cache_file,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            cache,
            file,
            indent=2
        )


